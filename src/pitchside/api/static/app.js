let wanted = null;

async function goto(seq) {
  wanted = Math.max(S.first, Math.min(S.last, seq));
  if (inflight) return;
  inflight = true;
  try {
    while (wanted !== null) {
      const s = wanted;
      wanted = null;
      const o = await api(`/api/matches/${S.matchId}/overlay?as_of_seq=${s}`);
      if (o.match_id !== S.matchId) continue;
      S.seq = s;
      S.overlay = o;
      applyOverlay();
    }
  } finally {
    inflight = false;
  }
}

function applyOverlay() {
  const o = S.overlay;
  $("#seq").value = S.seq;
  $("#home-score").textContent = o.score[S.meta.home.team_id];
  $("#away-score").textContent = o.score[S.meta.away.team_id];
  const done = S.seq >= S.last;
  $("#clock").textContent = done ? t("final") : o.minute;
  const w = o.win_probability;
  const pct = (p) => `${Math.round(100 * p)}%`;
  $("#wp-h").style.width = pct(w.home); $("#wp-d").style.width = pct(w.draw); $("#wp-a").style.width = pct(w.away);
  $("#wp-hl").textContent = `${S.meta.home.short_name} ${pct(w.home)}`;
  $("#wp-dl").textContent = `${t("draw")} ${pct(w.draw)}`;
  $("#wp-al").textContent = `${pct(w.away)} ${S.meta.away.short_name}`;
  $("#wp").setAttribute("aria-label", `${t("win_prob")}: ${$("#wp-hl").textContent}, ${$("#wp-dl").textContent}, ${$("#wp-al").textContent}`);
  const played = done ? 1 : Math.min(1, ((o.period - 1) * 2700 + o.clock_s) / 5400);
  $("#ring").setAttribute("stroke-dasharray", `${(43.98 * played).toFixed(2)} 44`);
  if (!S.scene) renderLive();
  renderChapters();
  renderFeed();
  if (S.focus && Math.abs(S.seq - S.focusSeq) >= 30) loadFocus();
  if (S.seq >= S.last) pause();
}

function play() {
  if (S.seq >= S.last) goto(S.first);
  if (S.scene) closeScene();
  S.playing = true;
  $("#play-icon").setAttribute("d", "M1 1 H5 V15 H1 z M9 1 H13 V15 H9 z");
  $("#play").setAttribute("aria-label", "Pause");
  clearInterval(S.timer);
  S.timer = setInterval(() => goto(S.seq + Number($("#speed").value)), 350);
}

function pause() {
  S.playing = false;
  $("#play-icon").setAttribute("d", "M1 1 L13 8 L1 15 z");
  $("#play").setAttribute("aria-label", "Play");
  clearInterval(S.timer);
}

// Timeline marks: only stories already on air (no spoilers); home above, away below.
function renderChapters() {
  const span = S.last - S.first || 1;
  const at = (seq) => (100 * (seq - S.first)) / span;
  $("#tl-played").style.width = `${at(S.seq)}%`;
  $("#chapters").innerHTML = S.chapters.filter((s) => s.aired_at_seq <= S.seq).map((s) => {
    const glyph = { decisive_run: "g-run", goal: "g-goal" }[s.kind] ?? "g-tick";
    const row = { home: "up", away: "down" }[sideOf(s.team_id)] ?? "mid";
    return `<i class="${glyph} ${row}" style="left:${at(s.seq)}%" title="${esc(s.headline[S.lang])}"></i>`;
  }).join("");
}

async function nextStory(kind) {
  const next = S.chapters.find((s) => s.aired_at_seq > S.seq && (!kind || s.kind === kind));
  if (!next) return;
  pause();
  await goto(next.aired_at_seq);
  selectStory(next);
}

// --- feed --------------------------------------------------------------------------

function renderFeed() {
  const stories = S.overlay.stories;
  const feed = $("#feed");
  if (!stories.length) {
    feed.innerHTML = `<li class="empty">${t("nothing_yet")}</li>`;
    return;
  }
  feed.innerHTML = "";
  // Air the newest story when it has just gone out (not after a long jump).
  const newest = stories[0];
  if (!S.seen.has(newest.story_id) && S.seq - newest.aired_at_seq <= 30) airStory(newest);
  for (const s of stories) {
    const li = document.createElement("li");
    const fresh = !S.seen.has(s.story_id);
    S.seen.add(s.story_id);
    li.className = [sideOf(s.team_id), fresh ? "fresh" : "",
      S.selected?.story?.story_id === s.story_id ? "sel" : ""].join(" ");
    const minute = factValue(s, "minute")?.display ?? "";
    li.innerHTML = `<button type="button"><span class="kind"><span>${esc(t("kinds")[s.kind] ?? s.kind)}</span>`
      + `<span>${esc(minute)}</span></span>${esc(s.headline[S.lang])}</button>`;
    li.querySelector("button").addEventListener("click", () => selectStory(s));
    feed.appendChild(li);
  }
}

// --- desk --------------------------------------------------------------------------

// [path, body] of the desk request; stories are built server-side, so precomputed
// answers (scripts/precompute_insights.py) share their cache key.
function turnFor(sel, persona) {
  const base = `/api/matches/${S.matchId}`;
  if (sel.type === "story") {
    return [`${base}/stories/${encodeURIComponent(sel.story.story_id)}/insights`,
            { persona, language: S.lang }];
  }
  return [`${base}/insights`, { as_of_seq: sel.seq, kind: sel.type, persona,
                                language: S.lang, question: sel.question ?? null }];
}

function forgetErrors() {  // a failed request is retried when the viewer asks again
  for (const [key, entry] of S.insights) if (entry.state === "error") S.insights.delete(key);
}

function selectStory(story) {
  forgetErrors();
  S.selected = { type: "story", story };
  S.sentence = null;
  if (story.ghost) openScene(story);
  else if (S.scene) closeScene();
  else renderLower();
  renderFeed();
  renderDesk();
}

function ask(type, question) {
  pause();
  forgetErrors();
  S.selected = { type, seq: S.seq, question };
  S.sentence = null;
  renderDesk();
}

function insightFor([path, body]) {
  const key = JSON.stringify([path, body]);
  if (!S.insights.has(key)) {
    const entry = { state: "loading" };
    S.insights.set(key, entry);
    api(path, body)
      .then((insight) => { entry.state = "done"; entry.insight = insight; })
      .catch((err) => { entry.state = "error"; entry.status = err.status; })
      .finally(() => renderDesk());
    return entry;
  }
  return S.insights.get(key);
}

function statusBadge(insight) {
  const cls = { verified: "verified", verified_after_retry: "retry" }[insight.status] ?? "evidence";
  const label = { verified: t("verified"), verified_after_retry: t("retry") }[insight.status]
    ?? t("evidence_only");
  const check = insight.status === "evidence_only" ? ""
    : '<svg width="12" height="12" viewBox="0 0 12 12" aria-hidden="true"><path d="M1.5 6.5 L4.5 9.5 L10.5 2.5"/></svg>';
  return `<span class="badge ${cls}">${check}${label}</span>`;
}

function renderTake(persona, entry, idx) {
  const head = S.compare ? `<h3>${t(persona)}</h3>` : "";
  if (entry.state === "loading") {
    return `<div class="take">${head}<p class="writing">${t("writing")}<span class="dots"></span></p></div>`;
  }
  if (entry.state === "error") {
    return `<div class="take">${head}<p class="fine">${entry.status === 429 ? t("busy") : t("error")}</p></div>`;
  }
  const ins = entry.insight;
  let body;
  if (ins.status === "evidence_only") {
    const why = (ins.failure ?? "").includes("no model configured") ? t("no_model")
      : (ins.failure ?? "").includes("verification twice") ? t("failed") : t("hidden");
    body = `<p class="fine">${why}</p>` + factsTable(ins.evidence);
  } else {
    body = "<p>" + ins.sentences.map((s, i) =>
      `<span class="sentence ${s.kind} ${S.sentence?.take === idx && S.sentence.i === i ? "sel" : ""}"
             data-take="${idx}" data-i="${i}">${esc(s.text)}</span>`).join(" ") + "</p>";
  }
  const trace = [`${ins.attempts} ${t("attempts")}`, ins.model ? `${t("model")}: ${ins.model}` : "",
    ins.tokens ? `${ins.tokens} ${t("tokens")}` : ""].filter(Boolean).join(" · ");
  const notes = ins.notes.map((n) => `<li>${esc(n)}</li>`).join("");
  return `<div class="take"><h3>${S.compare ? t(persona) : ""} ${statusBadge(ins)}</h3>${body}
    <ul class="trace"><li>${trace}</li>${notes}</ul></div>`;
}

function renderDesk() {
  const sel = S.selected;
  const body = $("#desk-body");
  if (!sel) {
    body.innerHTML = `<p class="fine">${t("desk_empty")}</p>`;
    return;
  }
  let top = "";
  if (sel.type === "story") {
    top = `<div class="instant" id="instant">${esc(sel.story.headline[S.lang])}<small>${t("instant")}</small></div>`;
  } else {
    top = `<div class="instant">${esc(sel.type === "recap" ? t("recap") : sel.question)}<small>${esc(sel.type === "recap" ? "" : t("question"))}</small></div>`;
  }
  const personas = S.compare ? ["casual", "analyst"] : [S.persona];
  const entries = personas.map((p) => insightFor(turnFor(sel, p)));
  body.innerHTML = top + `<div class="cols ${S.compare ? "two" : ""}">`
    + personas.map((p, i) => renderTake(p, entries[i], i)).join("") + "</div>";
  body.querySelectorAll(".sentence.claim").forEach((el) => el.addEventListener("click", () => {
    S.sentence = { take: Number(el.dataset.take), i: Number(el.dataset.i) };
    renderDesk();
    showEvidence(entries[S.sentence.take].insight, S.sentence.i);
  }));
  $("#instant")?.addEventListener("click", () => showTemplateEvidence(sel.story));
}

// --- evidence ----------------------------------------------------------------------

function factsTable(facts) {
  return "<table>" + facts.map((f) =>
    `<tr><td class="v">${esc(num(f.display))}</td><td>${esc(f.label)}<br><code>${esc(f.evidence_id)}</code></td></tr>`,
  ).join("") + "</table>";
}

function toolBlock(r) {
  const list = (items, cls) => (items.length
    ? `<ul class="${cls}">${items.map((c) => `<li>${esc(c)}</li>`).join("")}</ul>` : "");
  return `<div class="tool"><b>${t("tool")}: ${esc(r.tool_name)}</b> · ${t("sample")} ${r.sample_size}
    <div class="fine">${t("method")}: ${esc(r.method)}</div>
    ${r.caveats.length ? `<div>${t("caveats")}</div>${list(r.caveats, "")}` : ""}
    ${r.cannot_tell.length ? `<div>${t("cannot")}</div>${list(r.cannot_tell, "cannot")}` : ""}</div>`;
}

function showEvidence(insight, i) {
  const s = insight.sentences[i];
  const ids = new Set(s.evidence_ids);
  const facts = insight.evidence.filter((f) => ids.has(f.evidence_id));
  const tools = insight.results.filter((r) => r.facts.some((f) => ids.has(f.evidence_id)));
  const panel = $("#evidence");
  panel.hidden = false;
  panel.innerHTML = `<h2>${t("evidence")}</h2><p class="fine">${t("cited")}</p>`
    + factsTable(facts) + tools.map(toolBlock).join("");
}

function showTemplateEvidence(story) {
  const panel = $("#evidence");
  panel.hidden = false;
  panel.innerHTML = `<h2>${t("evidence")}</h2><p class="fine">${t("template_ev")}</p>`
    + factsTable(story.facts);
}

// --- fact-check a line ---------------------------------------------------------------

async function checkLine(text) {
  const body = $("#check-body");
  body.innerHTML = `<p class="writing">…</p>`;
  const r = await api(`/api/matches/${S.matchId}/check`,
    { text, as_of_seq: S.seq, language: S.lang }).catch(() => null);
  if (!r) { body.innerHTML = `<p class="fine">${t("error")}</p>`; return; }
  const cls = { verified: "verified", flagged: "flagged" }[r.verdict] ?? "evidence";
  const label = { verified: t("check_verified"), flagged: t("check_flagged") }[r.verdict]
    ?? t("check_nothing");
  // The line with each checked number marked by its status, in order.
  let html = "", rest = r.text;
  for (const n of r.numbers) {
    const at = rest.indexOf(n.raw);
    if (at < 0) continue;
    html += esc(rest.slice(0, at)) + `<span class="num ${n.status}">${esc(n.raw)}</span>`;
    rest = rest.slice(at + n.raw.length);
  }
  html += esc(rest);
  const facts = (fs) => fs.map((f) =>
    `<div><b>${esc(num(f.display))}</b> ${esc(f.label)} <code>${esc(f.evidence_id)}</code></div>`).join("");
  const items = r.numbers.map((n) => `<li class="${n.status}"><b>${esc(n.raw)}</b>: ${t(`st_${n.status}`)}
    ${facts(n.matches)}${n.data_says.length ? `<div class="fine">${t("data_says")}:</div>${facts(n.data_says)}` : ""}</li>`)
    .concat(r.misspelled.map((m) => `<li class="unsupported">${t("misspelled")}: ${esc(m)}</li>`)).join("");
  body.innerHTML = `<span class="badge ${cls}">${label}</span>
    <p class="check-line">${html}</p><ul class="check-list">${items}</ul>`;
}

// --- player focus ------------------------------------------------------------------

function setFocus(pid) {
  S.focus = pid === S.focus ? "" : pid;
  $("#focus").value = S.focus;
  S.focusSeq = -1;
  if (S.scene) renderScene(); else renderLive();
  loadFocus();
}

async function loadFocus() {
  const card = $("#focus-card");
  if (!S.focus) { card.hidden = true; return; }
  S.focusSeq = S.seq;
  const pid = S.focus;
  const r = await api(`/api/matches/${S.matchId}/tools/player_focus`,
    { as_of_seq: S.seq, player_id: pid }).catch(() => null);
  if (!r || pid !== S.focus) return;
  const p = S.players[pid];
  const by = Object.fromEntries(r.facts.map((f) => [suffix(f), f]));
  const stats = Object.entries(FOCUS_STATS).filter(([k]) => by[k]).map(([k, labels]) =>
    `<div><b>${esc(num(by[k].display))}</b><span>${labels[S.lang === "es" ? 1 : 0]}</span></div>`).join("");
  card.hidden = false;
  card.innerHTML = `<div><b>${esc(p.name)}</b> #${p.shirt} · ${esc(p.teamName)}</div>
    <div class="stats">${stats}</div>
    <button class="ghost-btn" id="ask-player">${t("ask_player")} ${esc(p.name)}</button>`;
  $("#ask-player").addEventListener("click", () =>
    ask("question", S.lang === "es" ? `¿Cómo está jugando ${p.name} (${p.teamName})?`
      : `How is ${p.name} (${p.teamName}) playing?`));
}

// --- match loading -----------------------------------------------------------------

async function loadMatch(matchId) {
  pause();
  S.matchId = matchId;
  S.meta = await api(`/api/matches/${matchId}`);
  S.first = S.meta.first_seq;
  S.last = S.meta.last_seq;
  S.players = {};
  for (const team of [S.meta.home, S.meta.away]) {
    for (const p of team.players) {
      S.players[p.player_id] = { name: p.name, shirt: p.shirt_number, team: team.team_id, teamName: team.name };
    }
  }
  S.selected = null; S.scene = null; S.focus = ""; S.seen = new Set(); S.airing = null;
  S.trailSeen = null;
  $("#scene-ctl").hidden = true;
  $("#evidence").hidden = true;
  $("#check-body").innerHTML = "";
  $("#focus-card").hidden = true;
  $("#players").innerHTML = "";
  $("#home-code").textContent = S.meta.home.short_name;
  $("#away-code").textContent = S.meta.away.short_name;
  $("#home-code").title = S.meta.home.name;
  $("#away-code").title = S.meta.away.name;
  $("#seq").min = S.first;
  $("#seq").max = S.last;
  $("#focus").innerHTML = `<option value="">${t("nobody")}</option>` + [S.meta.home, S.meta.away].map((team) =>
    `<optgroup label="${esc(team.name)}">${team.players.map((p) =>
      `<option value="${p.player_id}">#${p.shirt_number} ${esc(p.name)}</option>`).join("")}</optgroup>`).join("");
  S.chapters = await api(`/api/matches/${matchId}/stories`);
  renderChapters();
  renderDesk();
  await goto(S.first);
}

function wire() {
  $("#match").addEventListener("change", (e) => loadMatch(e.target.value));
  document.querySelectorAll("#persona button").forEach((b) => b.addEventListener("click", () => {
    S.persona = b.dataset.v; setSeg("persona", S.persona); renderDesk();
  }));
  document.querySelectorAll("#lang button").forEach((b) => b.addEventListener("click", () => {
    S.lang = b.dataset.v; setSeg("lang", S.lang); applyI18n(); renderChapters();
    if (S.overlay) { renderFeed(); renderLower(); }
    if (S.scene) renderScene();
    if (S.focus) loadFocus();
    renderDesk();
  }));
  $("#compare").addEventListener("change", (e) => { S.compare = e.target.checked; renderDesk(); });
  $("#focus").addEventListener("change", (e) => setFocus(e.target.value));
  $("#play").addEventListener("click", () => (S.playing ? pause() : play()));
  $("#seq").addEventListener("input", (e) => { pause(); if (S.scene) closeScene(); goto(Number(e.target.value)); });
  $("#next").addEventListener("click", () => nextStory());
  $("#next-goal").addEventListener("click", () => nextStory("goal"));
  $("#cam").addEventListener("click", () => {
    CAM.on = !CAM.on;
    setupCamera();
    rerenderPitch();
  });
  new ResizeObserver(() => { setupCamera(); rerenderPitch(); }).observe($(".pitch-wrap"));
  $("#full").addEventListener("click", () => {
    if (document.fullscreenElement) document.exitFullscreen();
    else $(".stage").requestFullscreen?.();
  });
  $("#check-form").addEventListener("submit", (e) => {
    e.preventDefault();
    const text = $("#check-text").value.trim();
    if (text) checkLine(text);
  });
  $("#check-example").addEventListener("click", () => {
    $("#check-text").value = t("example_line")(S.meta.away.name);
    checkLine($("#check-text").value);
  });
  $("#scene-exit").addEventListener("click", closeScene);
  document.querySelectorAll("#scene-toggle button").forEach((b) => b.addEventListener("click", () => {
    S.sceneMode = b.dataset.v; renderScene();
  }));
  $("#how").addEventListener("click", () => $("#how-dialog").showModal());
  $("#recap").addEventListener("click", () => ask("recap"));
  $("#ask").addEventListener("submit", (e) => {
    e.preventDefault();
    const q = $("#question").value.trim();
    if (q) { ask("question", q); $("#question").value = ""; }
  });
  document.addEventListener("keydown", (e) => {
    if (e.target.matches("input, select")) return;
    if (e.code === "Space") { e.preventDefault(); S.playing ? pause() : play(); }
    if (e.key === "n") nextStory();
    if (e.key === "g") nextStory("goal");
  });
  const defs = document.createElementNS(SVGNS, "defs");
  const marker = (id, color) => `<marker id="${id}" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="4"
    markerHeight="4" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${color}"/></marker>`;
  defs.innerHTML = marker("arrow", "#6fdca0") + marker("arrow-home", "#5ab4ff") + marker("arrow-away", "#ff8a3d");
  $("#pitch").prepend(defs);
}

