// Broadcast camera. The pitch SVG is tilted with CSS 3D (`translateZ(-k) rotateX(t)` under
// a `perspective` of P px on .pitch-wrap); `project` repeats that maths so players, drawn
// upright in the flat #figures layer, land exactly on the tilted grass and shrink with
// distance. k pushes the pitch back so its near edge keeps its width. Off = t = 0.
const CAM = { on: true, tilt: (24 * Math.PI) / 180, W: 0, H: 0, P: 1, k: 0 };
const VIEW = { x0: -3, y0: -3, w: 111, h: 74 };  // #pitch viewBox, metres

function setupCamera() {
  const svg = $("#pitch");
  CAM.W = svg.clientWidth;  // layout size: CSS transforms do not change it
  CAM.H = svg.clientHeight;
  CAM.P = 1.6 * CAM.W;
  const t = CAM.on ? CAM.tilt : 0;
  CAM.k = (CAM.H / 2) * Math.sin(t);
  $(".pitch-wrap").style.perspective = `${CAM.P}px`;
  $(".pitch-wrap").classList.toggle("cam3d", CAM.on);
  svg.style.transform = CAM.on ? `translateZ(${-CAM.k}px) rotateX(${t}rad)` : "none";
  $("#figures").setAttribute("viewBox", `0 0 ${CAM.W} ${CAM.H}`);
  $("#cam").setAttribute("aria-pressed", String(CAM.on));
}

/** Pitch metres -> screen px in #figures, and the scale of one metre there. */
function project(mx, my) {
  const { W, H, P, k } = CAM;
  const t = CAM.on ? CAM.tilt : 0;
  const X = ((mx - VIEW.x0) * W) / VIEW.w - W / 2;
  const Y = ((svgY(my) - VIEW.y0) * H) / VIEW.h - H / 2;
  const z = Y * Math.sin(t) - k;
  const f = P / (P - z);
  return { x: W / 2 + X * f, y: H / 2 + Y * Math.cos(t) * f, s: (f * W) / VIEW.w };
}

function rerenderPitch() {
  if (!S.overlay) return;
  if (S.scene) renderScene(); else renderLive();
}

function renderPlayers(dots, opts = {}) {
  if (!CAM.W) setupCamera();
  const layer = $("#players");
  const keep = new Set();
  for (const d of dots) {
    keep.add(d.player_id);
    let g = layer.querySelector(`[data-id="${d.player_id}"]`);
    if (!g) {
      g = document.createElementNS(SVGNS, "g");
      g.dataset.id = d.player_id;
      g.innerHTML = `<circle r="1.6"/><text>${d.shirt_number}</text>`;
      g.addEventListener("click", () => setFocus(d.player_id));
      layer.appendChild(g);
    }
    let { x, y } = d;
    if (opts.runner === d.player_id && opts.at) ({ x, y } = opts.at);
    const q = project(x, y);
    g.style.transform = `translate(${q.x.toFixed(1)}px, ${q.y.toFixed(1)}px) scale(${q.s.toFixed(3)})`;
    g.setAttribute("class", [
      "p", teamOf(d.player_id),
      S.focus === d.player_id ? "focus" : "",
      opts.runner === d.player_id ? "runner" : "",
      opts.scene && ![opts.runner, opts.recipient, opts.passer].includes(d.player_id) ? "dim" : "",
    ].join(" "));
  }
  layer.querySelectorAll("g").forEach((g) => { if (!keep.has(g.dataset.id)) g.remove(); });
  $("#figures").classList.toggle("scene", !!opts.scene);
}

// The ball glides like the players (same CSS transition), so neither lags the other.
function setBall(x, y) {
  $("#ball").style.transform = `translate(${x}px, ${y}px)`;
}

// Telestrator: the current move behind the ball. A new arrow fades in over the same
// time the players take to glide to their new spots, so it never arrives first.
function trailItem(it) {
  const side = sideOf(it.team_id) || "home";
  const sx = it.start.x, sy = svgY(it.start.y);
  if (it.kind === "ball_won") return `<circle class="tr-won tr ${side}" cx="${sx}" cy="${sy}" r="1.9"/>`;
  const from = it.age_s > 0  // where the passer or shooter stood then
    ? `<circle class="tr-from tr ${side}" cx="${sx}" cy="${sy}" r="1.4"/>` : "";
  const ex = it.end.x, ey = svgY(it.end.y);
  if (it.kind === "shot") {
    return `${from}<line class="tr shot" x1="${sx}" y1="${sy}" x2="${ex}" y2="${ey}" marker-end="url(#arrow)"/>`
      + `<text class="tr-label" x="${sx + 1.2}" y="${sy - 1.4}">xG ${num(it.xg.toFixed(2))}</text>`;
  }
  const failed = it.outcome !== "complete";
  const cross = failed ? `<path class="tr tr-x ${side}" d="M${ex - 0.8},${ey - 0.8} L${ex + 0.8},${ey + 0.8} M${ex - 0.8},${ey + 0.8} L${ex + 0.8},${ey - 0.8}"/>` : "";
  return `${from}<line class="tr ${side} ${failed ? "failed" : ""}" x1="${sx}" y1="${sy}" x2="${ex}" y2="${ey}"`
    + ` ${failed ? "" : `marker-end="url(#arrow-${side})"`}/>${cross}`;
}

function renderTrail(items) {
  const seen = S.trailSeen ?? new Set();
  $("#trail").innerHTML = items.map((it) => {
    const fade = Math.max(0.4, 1 - (it.age_s / 6) * 0.6).toFixed(2);
    return `<g class="${seen.has(it.seq) ? "" : "tr-new"}" opacity="${fade}">${trailItem(it)}</g>`;
  }).join("");
  S.trailSeen = new Set(items.map((it) => it.seq));
}

function renderLive() {
  const o = S.overlay;
  if (!o) return;
  $("#scene").innerHTML = "";
  renderTrail(o.trail);
  renderPlayers(o.players);
  renderLower();
  const e = o.last_event;
  // Players are drawn as they stood at this event, so the ball is at its location: the
  // passer's feet for a pass (the arrow shows where it goes), not where it will land.
  const ball = e.location;
  setBall(ball.x, svgY(ball.y));
  $("#pass-line").style.display = "none";  // the trail draws the latest pass
}

function factValue(story, name) { return story.facts.find((f) => suffix(f) === name); }

function sideOf(teamId) {
  if (!teamId) return "";
  return teamId === S.meta.home.team_id ? "home" : "away";
}

const ON_AIR_MS = 8000;  // a newly aired story's lower third, like a broadcast graphic

// A story that has just aired takes the lower third for ON_AIR_MS, then clears.
function airStory(story) {
  S.airing = { story, until: performance.now() + ON_AIR_MS };
  clearTimeout(S.airTimer);
  S.airTimer = setTimeout(renderLower, ON_AIR_MS + 50);
  renderLower();
}

// The lower third: the story being replayed, else the one picked, else one on air now.
function renderLower() {
  const airing = S.airing && performance.now() < S.airing.until ? S.airing.story : null;
  const story = S.scene ?? S.selected?.story ?? airing;
  const lower = $("#lower");
  if (!story) { lower.hidden = true; return; }
  lower.hidden = false;
  const minute = factValue(story, "minute")?.display ?? "";
  const kicker = $("#lower-kicker");
  kicker.textContent = `${t("kinds")[story.kind] ?? story.kind} · ${minute}`;
  kicker.className = `kicker ${story.kind === "decisive_run" ? "" : story.kind === "goal" ? "goal" : "plain"}`;
  $("#lower-body").className = `lower-body ${sideOf(story.team_id)}`;
  const team = story.team_id === S.meta.home.team_id ? S.meta.home : story.team_id ? S.meta.away : null;
  let name;
  if (story.kind === "decisive_run") {
    const p = S.players[story.player_id];
    name = `${esc(p.name)} <small>#${p.shirt} · ${esc(team.name)}</small>`;
  } else if (story.kind === "goal") {
    name = `${esc(S.meta.home.name)} ${esc(factValue(story, "scoreline").display)} ${esc(S.meta.away.name)}`;
  } else {
    name = team ? esc(team.name) : `${esc(S.meta.home.short_name)} v ${esc(S.meta.away.short_name)}`;
  }
  $("#lower-name").innerHTML = name;
  $("#lower-text").textContent = story.headline[S.lang];
  $("#meters").hidden = !S.scene;
}

function renderScene() {
  const story = S.scene;
  const g = story.ghost;
  const withRun = S.sceneMode === "with";
  const at = withRun ? g.with_xy : g.without_xy;
  const other = withRun ? g.without_xy : g.with_xy;
  const target = withRun || g.player_id !== g.recipient_id ? g.pass_to : {
    x: g.pass_to.x - (g.with_xy.x - g.without_xy.x), y: g.pass_to.y - (g.with_xy.y - g.without_xy.y),
  };
  const near = (d) => Math.hypot(d.x - g.pass_from.x, d.y - g.pass_from.y);
  const passer = g.frame.filter((d) => d.team_id === story.team_id)
    .reduce((a, b) => (near(b) < near(a) ? b : a)).player_id;
  $("#trail").innerHTML = "";
  renderPlayers(g.frame, { scene: true, runner: g.player_id, recipient: g.recipient_id, passer, at });
  $("#scene").innerHTML = `
    <circle class="target" cx="${target.x}" cy="${svgY(target.y)}" r="2.6"/>
    <circle class="ghost-dot" cx="${other.x}" cy="${svgY(other.y)}" r="1.6"/>
    <line class="run-arrow" x1="${g.without_xy.x}" y1="${svgY(g.without_xy.y)}"
          x2="${g.with_xy.x}" y2="${svgY(g.with_xy.y)}"/>`;
  const line = $("#pass-line");
  line.setAttribute("x1", g.pass_from.x); line.setAttribute("y1", svgY(g.pass_from.y));
  line.setAttribute("x2", target.x); line.setAttribute("y2", svgY(target.y));
  line.setAttribute("class", "pass complete");
  line.style.display = "";
  setBall(g.pass_from.x + 1.2, svgY(g.pass_from.y) - 1.2);  // at the passer's feet
  const cw = factValue(story, "control_with");
  const co = factValue(story, "control_without");
  $("#m-with").style.width = `${cw.value}%`;
  $("#m-without").style.width = `${co.value}%`;
  $("#v-with").textContent = num(cw.display);
  $("#v-without").textContent = num(co.display);
  $("#scene-chip").textContent = `${t("replay")} · ${factValue(story, "minute")?.display ?? ""}`;
  $("#scene-ctl").hidden = false;
  setSeg("scene-toggle", S.sceneMode);
  renderLower();
}

function openScene(story) {
  pause();
  S.scene = story;
  S.sceneMode = "without";
  renderScene();
  setTimeout(() => { if (S.scene === story) { S.sceneMode = "with"; renderScene(); } }, 700);
}

function closeScene() {
  S.scene = null;
  $("#scene-ctl").hidden = true;
  renderLive();
}

