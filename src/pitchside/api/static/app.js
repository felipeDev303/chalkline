function teamOf(pid) { return S.players[pid]?.team === S.meta.home.team_id ? "home" : "away"; }

function renderPlayers(dots, opts = {}) {
  const layer = $("#players");
  const keep = new Set();
  for (const d of dots) {
    keep.add(d.player_id);
    let g = layer.querySelector(`[data-id="${d.player_id}"]`);
    if (!g) {
      g = document.createElementNS(SVGNS, "g");
      g.dataset.id = d.player_id;
      g.innerHTML = `<circle r="1.6"/><text>${d.shirt_number}</text>`;
      g.addEventListener("click", () => setFocus(d.player_id));
      layer.appendChild(g);
    }
    let { x, y } = d;
    if (opts.runner === d.player_id && opts.at) ({ x, y } = opts.at);
    g.style.transform = `translate(${x}px, ${svgY(y)}px)`;
    g.setAttribute("class", [
      "p", teamOf(d.player_id),
      S.focus === d.player_id ? "focus" : "",
      opts.runner === d.player_id ? "runner" : "",
      opts.scene && opts.runner !== d.player_id && opts.recipient !== d.player_id ? "dim" : "",
    ].join(" "));
  }
  layer.querySelectorAll("g").forEach((g) => { if (!keep.has(g.dataset.id)) g.remove(); });
  $("#pitch").classList.toggle("scene", !!opts.scene);
}

function renderLive() {
  const o = S.overlay;
  if (!o) return;
  $("#scene").innerHTML = "";
  renderPlayers(o.players);
  const e = o.last_event;
  const ball = e.type === "pass" && e.outcome === "complete" ? e.end_location : e.location;
  $("#ball").setAttribute("cx", ball.x);
  $("#ball").setAttribute("cy", svgY(ball.y));
  const line = $("#pass-line");
  if (e.type === "pass") {
    line.setAttribute("x1", e.location.x); line.setAttribute("y1", svgY(e.location.y));
    line.setAttribute("x2", e.end_location.x); line.setAttribute("y2", svgY(e.end_location.y));
    line.setAttribute("class", `pass ${e.outcome === "complete" ? "complete" : ""}`);
    line.style.display = "";
  } else {
    line.style.display = "none";
  }
}

function factValue(story, name) { return story.facts.find((f) => suffix(f) === name); }

function renderScene() {
  const story = S.scene;
  const g = story.ghost;
  const withRun = S.sceneMode === "with";
  const at = withRun ? g.with_xy : g.without_xy;
  const other = withRun ? g.without_xy : g.with_xy;
  const target = withRun || g.player_id !== g.recipient_id ? g.pass_to : {
    x: g.pass_to.x - (g.with_xy.x - g.without_xy.x), y: g.pass_to.y - (g.with_xy.y - g.without_xy.y),
  };
  renderPlayers(g.frame, { scene: true, runner: g.player_id, recipient: g.recipient_id, at });
  $("#scene").innerHTML = `
    <circle class="target" cx="${target.x}" cy="${svgY(target.y)}" r="2.6"/>
    <circle class="ghost-dot" cx="${other.x}" cy="${svgY(other.y)}" r="1.6"/>
    <line class="run-arrow" x1="${g.without_xy.x}" y1="${svgY(g.without_xy.y)}"
          x2="${g.with_xy.x}" y2="${svgY(g.with_xy.y)}"/>`;
  const line = $("#pass-line");
  line.setAttribute("x1", g.pass_from.x); line.setAttribute("y1", svgY(g.pass_from.y));
  line.setAttribute("x2", target.x); line.setAttribute("y2", svgY(target.y));
  line.setAttribute("class", "pass complete");
  line.style.display = "";
  $("#ball").setAttribute("cx", g.pass_from.x);
  $("#ball").setAttribute("cy", svgY(g.pass_from.y));
  const cw = factValue(story, "control_with");
  const co = factValue(story, "control_without");
  $("#scene-title").textContent = story.headline[S.lang];
  $("#m-with").style.width = `${cw.value}%`;
  $("#m-without").style.width = `${co.value}%`;
  $("#v-with").textContent = num(cw.display);
  $("#v-without").textContent = num(co.display);
  $("#scene-card").hidden = false;
  setSeg("scene-toggle", S.sceneMode);
}

function openScene(story) {
  pause();
  S.scene = story;
  S.sceneMode = "without";
  renderScene();
  setTimeout(() => { if (S.scene === story) { S.sceneMode = "with"; renderScene(); } }, 700);
}

function closeScene() {
  S.scene = null;
  $("#scene-card").hidden = true;
  renderLive();
}

// --- replay ------------------------------------------------------------------------

let inflight = false;
let wanted = null;

async function goto(seq) {
  wanted = Math.max(S.first, Math.min(S.last, seq));
  if (inflight) return;
  inflight = true;
  try {
    while (wanted !== null) {
      const s = wanted;
      wanted = null;
      const o = await api(`/api/matches/${S.matchId}/overlay?as_of_seq=${s}`);
      if (o.match_id !== S.matchId) continue;
      S.seq = s;
      S.overlay = o;
      applyOverlay();
    }
  } finally {
    inflight = false;
  }
}

function applyOverlay() {
  const o = S.overlay;
  $("#seq").value = S.seq;
  $("#home-score").textContent = o.score[S.meta.home.team_id];
  $("#away-score").textContent = o.score[S.meta.away.team_id];
  $("#clock").textContent = o.minute;
  if (!S.scene) renderLive();
  renderFeed();
  if (S.focus && Math.abs(S.seq - S.focusSeq) >= 30) loadFocus();
  if (S.seq >= S.last) pause();
}

function play() {
  if (S.seq >= S.last) goto(S.first);
  if (S.scene) closeScene();
  S.playing = true;
  $("#play").textContent = "❚❚";
  clearInterval(S.timer);
  S.timer = setInterval(() => goto(S.seq + Number($("#speed").value)), 350);
}

function pause() {
  S.playing = false;
  $("#play").textContent = "▶";
  clearInterval(S.timer);
}

function renderChapters() {
  const span = S.last - S.first || 1;
  $("#chapters").innerHTML = S.chapters.map((s) =>
    `<span class="${s.kind}" style="left:${(100 * (s.aired_at_seq - S.first)) / span}%"
       title="${esc(s.headline[S.lang])}"></span>`).join("");
}

async function nextStory() {
  const next = S.chapters.find((s) => s.aired_at_seq > S.seq);
  if (!next) return;
  pause();
  await goto(next.aired_at_seq);
  selectStory(next);
}

// --- feed --------------------------------------------------------------------------

function renderFeed() {
  const stories = S.overlay.stories;
  const feed = $("#feed");
  if (!stories.length) {
    feed.innerHTML = `<li class="empty">${t("nothing_yet")}</li>`;
    return;
  }
  feed.innerHTML = "";
  for (const s of stories) {
    const li = document.createElement("li");
    const side = s.team_id === S.meta.home.team_id ? "home" : s.team_id ? "away" : "";
    const fresh = !S.seen.has(s.story_id);
    S.seen.add(s.story_id);
    li.className = [side, fresh ? "fresh" : "",
      S.selected?.story?.story_id === s.story_id ? "sel" : ""].join(" ");
    li.innerHTML = `<div class="kind">${esc(t("kinds")[s.kind] ?? s.kind)}</div>${esc(s.headline[S.lang])}`;
    li.addEventListener("click", () => selectStory(s));
    feed.appendChild(li);
  }
}

