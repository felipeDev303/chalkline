"""Fitted models applied to events: expected goals (xG) and pass completion (xPass).

Coefficients come from metrics/_models.py, generated by scripts/fit_models.py on dev
seeds; scripts/calibrate.py checks them on held-out seeds against the simulator's
latent probabilities (docs/data/CALIBRATION.md).
"""

from __future__ import annotations

from pitchside.events.schema import MatchMetadata, Pass, Shot
from pitchside.metrics._models import XG, XPASS
from pitchside.metrics.features import xg_features, xpass_features

# How each xG feature reads in words, for facts and the evidence panel.
XG_EFFECT_LABELS = {
    "distance_m": "distance to goal",
    "angle_rad": "angle of the goal mouth",
    "header": "header",
    "under_pressure": "pressure on the shooter",
}


def xg(metadata: MatchMetadata, shot: Shot) -> float:
    """Probability that a shot like this one is a goal."""
    return XG.prob(xg_features(metadata, shot))


def xg_effects(metadata: MatchMetadata, shot: Shot) -> dict[str, float]:
    """Each feature's push on this shot's goal log-odds, against an average shot."""
    return XG.effects(xg_features(metadata, shot))


def xpass(metadata: MatchMetadata, p: Pass) -> float:
    """Probability that a pass like this one is completed."""
    return XPASS.prob(xpass_features(metadata, p))


def odds_one_in(probability: float) -> int:
    """'Goes in about 1 time in N' for a probability, N >= 1."""
    return max(1, round(1 / probability)) if probability > 0 else 0
