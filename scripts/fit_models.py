"""Fit the xG and xPass models on DEV seeds and write metrics/_models.py.

Usage: uv run python scripts/fit_models.py

Both are logistic regressions fitted by IRLS (Newton's method) in numpy, on the
features in metrics/features.py: xG predicts goal from a shot, xPass predicts a
completed pass. Also writes the league's goals per team per 90 minutes, the prior of
the win-probability model. Fitted on seeds 0-99 only; scripts/eval_models.py
evaluates on held-out seeds against the simulator's latent probabilities.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from detector_eval import DEV_SEEDS, TEST_SEEDS

from pitchside.metrics.features import (
    XG_FEATURES,
    XPASS_FEATURES,
    xg_features,
    xpass_features,
)
from pitchside.simulator import simulate_match

OUT = Path(__file__).resolve().parents[1] / "src" / "pitchside" / "metrics" / "_models.py"
ITERATIONS = 25
RIDGE = 1e-6  # keeps the Newton step defined if a feature is constant


def irls(x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Logistic regression weights (intercept first) by iteratively reweighted least squares."""
    design = np.column_stack([np.ones(len(x)), x])
    w = np.zeros(design.shape[1])
    for _ in range(ITERATIONS):
        p = 1.0 / (1.0 + np.exp(-design @ w))
        hessian = design.T @ (design * (p * (1 - p))[:, None]) + RIDGE * np.eye(len(w))
        w = w + np.linalg.solve(hessian, design.T @ (y - p))
    return w


def model_block(name: str, features: tuple[str, ...], w: np.ndarray, x: np.ndarray,
                n: int, positives: int) -> str:
    coefs = ", ".join(f"{c:.6f}" for c in w[1:])
    means = ", ".join(f"{m:.6f}" for m in x.mean(axis=0))
    names = "".join(f"        {f!r},\n" for f in features)
    return (
        f"{name} = Logistic(\n"
        f"    features=(\n{names}    ),\n"
        f"    intercept={w[0]:.6f},\n"
        f"    coefs=({coefs},),\n"
        f"    means=({means},),\n"
        f"    n_train={n},\n"
        f"    positives={positives},\n"
        f")\n"
    )


def main() -> None:
    assert not set(DEV_SEEDS) & set(TEST_SEEDS), "fitting must never see test seeds"
    shots_x, shots_y, passes_x, passes_y = [], [], [], []
    goals = 0
    for seed in DEV_SEEDS:
        match = simulate_match(seed)
        meta = match.metadata
        for e in match.events:
            if e.type == "shot":
                shots_x.append(xg_features(meta, e))
                shots_y.append(float(e.outcome == "goal"))
                goals += e.outcome == "goal"
            elif e.type == "pass":
                passes_x.append(xpass_features(meta, e))
                passes_y.append(float(e.outcome == "complete"))
    sx, sy = np.array(shots_x), np.array(shots_y)
    px, py = np.array(passes_x), np.array(passes_y)
    w_xg, w_xpass = irls(sx, sy), irls(px, py)
    goals_per_team_90 = goals / (2 * len(DEV_SEEDS))

    OUT.write_bytes((
        '"""Fitted models. GENERATED by scripts/fit_models.py - do not edit by hand.\n\n'
        f"Logistic regressions (IRLS, {ITERATIONS} iterations) on simulated seeds "
        f"{DEV_SEEDS[0]}-{DEV_SEEDS[-1]}.\n"
        "`means` are the training means of each feature: effects are measured from an\n"
        'average shot or pass.\n"""\n\n'
        "from pitchside.metrics._logistic import Logistic\n\n"
        + model_block("XG", XG_FEATURES, w_xg, sx, len(sy), int(sy.sum())) + "\n"
        + model_block("XPASS", XPASS_FEATURES, w_xpass, px, len(py), int(py.sum())) + "\n"
        + "# Goals per team per 90 minutes in the simulated league: the win-probability prior.\n"
        + f"GOALS_PER_TEAM_90 = {goals_per_team_90:.6f}\n"
    ).encode())
    print(f"wrote {OUT.name}: {len(sy)} shots ({int(sy.sum())} goals), {len(py)} passes; "
          f"{goals_per_team_90:.3f} goals per team per 90")
    print("xG  ", dict(zip(("intercept", *XG_FEATURES), np.round(w_xg, 3), strict=True)))
    print("xPass", dict(zip(("intercept", *XPASS_FEATURES), np.round(w_xpass, 3), strict=True)))


if __name__ == "__main__":
    main()
