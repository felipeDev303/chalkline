"""Fit the expected threat (xT) grid on DEV seeds and write metrics/_xt_grid.py.

Usage: uv run python scripts/fit_xt.py

xT (Singh, 2018) values a zone by the chance that possession from there ends in a
goal, with a Markov model of actions: xT(z) = s(z) g(z) + m(z) sum_z' T(z, z') xT(z'),
where s / m are the shares of shots and passes from z, g the goal rate of shots from
z and T(z, z') the rate of completed passes from z to z' (failed passes add 0).
Fitted on seeds 0-99 only; scripts/calibrate.py evaluates it on seeds 200-399.
"""

from __future__ import annotations

from pathlib import Path

from detector_eval import DEV_SEEDS, TEST_SEEDS

from pitchside.metrics._timeline import attack_frame
from pitchside.metrics.expected_threat import GRID_X, GRID_Y, zone_of
from pitchside.simulator import simulate_match

OUT = Path(__file__).resolve().parents[1] / "src" / "pitchside" / "metrics" / "_xt_grid.py"
ITERATIONS = 50


def main() -> None:
    assert not set(DEV_SEEDS) & set(TEST_SEEDS), "fitting must never see test seeds"
    n = GRID_X * GRID_Y
    shots, goals, moves = [0] * n, [0] * n, [0] * n
    trans = [[0] * n for _ in range(n)]
    for seed in DEV_SEEDS:
        match = simulate_match(seed)
        meta = match.metadata
        for e in match.events:
            if e.type not in ("pass", "shot"):
                continue
            z = zone_of(attack_frame(meta, e.team_id, e.period, e.location))
            if e.type == "shot":
                shots[z] += 1
                goals[z] += e.outcome == "goal"
            else:
                moves[z] += 1
                if e.outcome == "complete":
                    trans[z][zone_of(attack_frame(meta, e.team_id, e.period, e.end_location))] += 1

    xt = [0.0] * n
    for _ in range(ITERATIONS):
        nxt = []
        for z in range(n):
            actions = shots[z] + moves[z]
            if actions == 0:
                nxt.append(0.0)
                continue
            shoot = shots[z] / actions * (goals[z] / shots[z] if shots[z] else 0.0)
            move = sum(trans[z][t] * xt[t] for t in range(n)) / actions
            nxt.append(shoot + move)
        xt = nxt

    rows = [tuple(round(xt[x * GRID_Y + y], 5) for y in range(GRID_Y)) for x in range(GRID_X)]
    body = ",\n".join(f"    {row}," .rstrip(",") for row in rows)
    OUT.write_bytes((
        '"""Expected threat grid. GENERATED by scripts/fit_xt.py - do not edit by hand.\n\n'
        f"Fitted on simulated seeds {DEV_SEEDS[0]}-{DEV_SEEDS[-1]} "
        f"({sum(shots)} shots, {sum(moves)} passes), {ITERATIONS} iterations.\n"
        f"XT[x][y]: {GRID_X} zones along the attacking direction x {GRID_Y} across;\n"
        'value = probability that possession from that zone ends in a goal.\n"""\n\n'
        f"XT: tuple[tuple[float, ...], ...] = (\n{body},\n)\n"
    ).encode())
    peak = max(xt)
    print(f"wrote {OUT.name}: max xT {peak:.4f} at zone {xt.index(peak)}; "
          f"{sum(shots)} shots, {sum(moves)} passes")


if __name__ == "__main__":
    main()
